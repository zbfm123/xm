package com.demo.contract.rule.domain;

/**
 * 问题严重级别。
 *
 * <p>用途：排序与展示优先级。<b>不代表"能不能自动处理"</b>——
 * 那是 {@link RuleResult} 与人工复核流程的事。
 *
 * <p>级别目前凭业务常识设定，没有真实法务依据。这是**已知的弱点**：
 * 真实系统中级别应当来自业务方的风险清单。面试时应当如实说明。
 */
public enum Severity {

    /** 高风险：可能导致直接经济损失或责任失衡。 */
    HIGH,

    /** 中风险：条款不完整或表述模糊，需确认。 */
    MEDIUM,

    /** 低风险：形式问题，不构成实质风险。 */
    LOW
}
